"""Tenant isolation tests — S3 key scoping and cross-tenant prefix prevention.

These tests verify that every S3 object key generated by the system:
1. Always starts with the tenant_id as the first path segment
2. Cannot be manipulated to point to another tenant's prefix
3. Follows the expected key pattern: {tenant_id}/{service}/{resource_id}/{filename}
"""
import re

TENANT_A = "aaaaaaaa-aaaa-aaaa-aaaa-aaaaaaaaaaaa"
TENANT_B = "bbbbbbbb-bbbb-bbbb-bbbb-bbbbbbbbbbbb"

_S3_KEY_PATTERN = re.compile(
    r"^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}/"
    r"[a-z_-]+/"
    r".+"
)


# ---------------------------------------------------------------------------
# Key structure validation helpers
# ---------------------------------------------------------------------------


def _build_evidence_key(tenant_id: str, claim_id: str, filename: str) -> str:
    """Mirror how services.claims builds S3 evidence keys."""
    return f"{tenant_id}/claims/{claim_id}/{filename}"


def _build_manifest_key(tenant_id: str, manifest_id: str, filename: str) -> str:
    return f"{tenant_id}/manifests/{manifest_id}/{filename}"


def _build_packing_list_key(tenant_id: str, pl_id: str, filename: str) -> str:
    return f"{tenant_id}/packing-lists/{pl_id}/{filename}"


def _build_release_note_key(tenant_id: str, note_id: str, filename: str) -> str:
    return f"{tenant_id}/release-notes/{note_id}/{filename}"


def _build_data_cleanup_prefix(tenant_id: str) -> str:
    """Top-level prefix deleted during tenant offboarding."""
    return f"{tenant_id}/"


# ---------------------------------------------------------------------------
# Key structure tests
# ---------------------------------------------------------------------------


class TestS3KeyStructure:
    def test_evidence_key_starts_with_tenant_id(self):
        key = _build_evidence_key(TENANT_A, "claim-001", "damage.jpg")
        assert key.startswith(TENANT_A), f"Key {key!r} does not start with tenant_id"

    def test_manifest_key_starts_with_tenant_id(self):
        key = _build_manifest_key(TENANT_A, "manifest-001", "manifest.pdf")
        assert key.startswith(TENANT_A)

    def test_packing_list_key_starts_with_tenant_id(self):
        key = _build_packing_list_key(TENANT_A, "pl-001", "items.xlsx")
        assert key.startswith(TENANT_A)

    def test_release_note_key_starts_with_tenant_id(self):
        key = _build_release_note_key(TENANT_A, "note-001", "release.pdf")
        assert key.startswith(TENANT_A)

    def test_all_key_types_match_pattern(self):
        keys = [
            _build_evidence_key(TENANT_A, "claim-001", "photo.jpg"),
            _build_manifest_key(TENANT_A, "manifest-001", "doc.pdf"),
            _build_packing_list_key(TENANT_A, "pl-001", "list.xlsx"),
            _build_release_note_key(TENANT_A, "note-001", "note.pdf"),
        ]
        for key in keys:
            assert _S3_KEY_PATTERN.match(key), f"Key {key!r} does not match expected pattern"

    def test_data_cleanup_prefix_matches_tenant_id(self):
        prefix = _build_data_cleanup_prefix(TENANT_A)
        assert prefix == f"{TENANT_A}/"
        assert prefix.startswith(TENANT_A)


# ---------------------------------------------------------------------------
# Cross-tenant prefix prevention
# ---------------------------------------------------------------------------


class TestCrossTenantS3Prevention:
    def test_tenant_a_key_does_not_start_with_tenant_b(self):
        key = _build_evidence_key(TENANT_A, "claim-001", "photo.jpg")
        assert not key.startswith(TENANT_B)

    def test_tenant_b_key_does_not_start_with_tenant_a(self):
        key = _build_evidence_key(TENANT_B, "claim-002", "photo.jpg")
        assert not key.startswith(TENANT_A)

    def test_injected_path_traversal_is_not_a_valid_tenant_prefix(self):
        """Path traversal attempts must not produce keys starting with valid tenant_id."""
        malicious_filename = "../../../other-tenant-data/secret.txt"
        key = _build_evidence_key(TENANT_A, "claim-001", malicious_filename)
        # The key will contain the traversal attempt — the service should sanitize
        # filenames before use, but this test documents that the prefix is still
        # scoped to TENANT_A (traversal doesn't escape the tenant prefix position)
        assert key.startswith(TENANT_A)

    def test_cleanup_prefix_for_tenant_a_does_not_delete_tenant_b(self):
        """The prefix used for S3 bulk delete targets only TENANT_A's objects."""
        prefix_a = _build_data_cleanup_prefix(TENANT_A)
        prefix_b = _build_data_cleanup_prefix(TENANT_B)

        # A key belonging to TENANT_B must NOT match TENANT_A's prefix
        tenant_b_key = _build_evidence_key(TENANT_B, "claim-999", "evidence.jpg")
        assert not tenant_b_key.startswith(prefix_a)

        # And vice versa
        tenant_a_key = _build_evidence_key(TENANT_A, "claim-001", "photo.jpg")
        assert not tenant_a_key.startswith(prefix_b)

    def test_uuid_tenant_ids_are_distinct_prefixes(self):
        """Two UUID-format tenant IDs produce non-overlapping prefixes."""
        prefix_a = _build_data_cleanup_prefix(TENANT_A)
        prefix_b = _build_data_cleanup_prefix(TENANT_B)
        assert prefix_a != prefix_b
        assert not prefix_a.startswith(prefix_b[:8])
        assert not prefix_b.startswith(prefix_a[:8])


# ---------------------------------------------------------------------------
# Filename safety
# ---------------------------------------------------------------------------


class TestS3FilenameCharacters:
    """Verify safe filename patterns are distinct from path traversal attempts."""

    _SAFE_FILENAMES = [
        "damage_photo.jpg",
        "manifest-v2.pdf",
        "packing_list_2026.xlsx",
        "release_note_001.pdf",
    ]

    _DANGEROUS_FILENAMES = [
        "../secret.txt",
        "../../etc/passwd",
        "/absolute/path.txt",
        "file\x00name.jpg",   # null byte
    ]

    def test_safe_filenames_do_not_contain_traversal(self):
        for filename in self._SAFE_FILENAMES:
            assert ".." not in filename, f"Safe filename {filename!r} unexpectedly contains '..'"
            assert "/" not in filename
            assert not filename.startswith("/")

    def test_dangerous_filenames_are_detectable(self):
        for filename in self._DANGEROUS_FILENAMES:
            is_dangerous = (
                ".." in filename
                or filename.startswith("/")
                or "\x00" in filename
            )
            assert is_dangerous, f"Expected {filename!r} to be flagged as dangerous"


# ---------------------------------------------------------------------------
# S3 key uniqueness across tenants
# ---------------------------------------------------------------------------


class TestS3KeyUniqueness:
    def test_same_resource_id_in_different_tenants_produces_different_keys(self):
        """Same claim_id in two tenants must produce different S3 keys."""
        claim_id = "claim-001"
        filename = "damage.jpg"

        key_a = _build_evidence_key(TENANT_A, claim_id, filename)
        key_b = _build_evidence_key(TENANT_B, claim_id, filename)

        assert key_a != key_b
        assert key_a.startswith(TENANT_A)
        assert key_b.startswith(TENANT_B)

    def test_presigned_url_scope_enforced_by_prefix(self):
        """Presigned URL generation scoped to tenant prefix can be verified."""
        # The S3 key prefix MUST equal the tenant_id — any presigned URL
        # generated by the system will contain this tenant_id prefix in the key
        tenant_a_keys = [
            _build_evidence_key(TENANT_A, f"claim-{i:03d}", "photo.jpg")
            for i in range(5)
        ]
        for key in tenant_a_keys:
            # All keys for TENANT_A start with TENANT_A — bucket policy can enforce this
            assert key.split("/")[0] == TENANT_A
