/**
 * Tenant-branded header/footer for the A4 print documents (4.1 branding_config
 * consumers). Falls back to the ShipX platform lockup when the tenant hasn't
 * set a display name yet, so documents never render with a blank brand.
 *
 * Uses useBranding() — GET /v1/tenant/config is readable by every staff role
 * precisely so these documents can render for whoever prints them.
 */
import type { JSX } from 'react'
import { type BrandingConfig } from '../../api/tenantManagement'
import { KolaMark, ShipxWordmark } from '../../design/components'
import { TenantLogo } from '../../shell/TenantLogo'
import styles from './print.module.css'


export function PrintBrandHead({ branding }: { branding: BrandingConfig | null }): JSX.Element {
  const name = branding?.display_name?.trim()
  if (!name) {
    return (
      <div className={styles.brand}>
        <KolaMark size={28} color="#1c7922" />
        <ShipxWordmark size={20} color="#1c1b1c" />
      </div>
    )
  }
  return (
    <div className={styles.brand}>
      {/* The uploaded logo, or the initials on the brand colour (FD-29). */}
      <TenantLogo
        name={name}
        color={branding?.primary_color}
        logoUrl={branding?.logo_url}
        className={styles.brandTile}
        fallbackColor="#1c7922"
      />
      <div>
        <div className={styles.brandName}>{name}</div>
        {branding?.tagline?.trim() && <div className={styles.brandTagline}>{branding.tagline}</div>}
      </div>
    </div>
  )
}

/** Tenant boilerplate above the "Generated by ShipX" attribution line. */
export function PrintBrandFoot({ branding }: { branding: BrandingConfig | null }): JSX.Element | null {
  const footer = branding?.document_footer?.trim()
  if (!footer) return null
  return (
    <div className={styles.tenantFoot}>
      {footer.split('\n').map((line, i) => (
        <div key={i}>{line}</div>
      ))}
    </div>
  )
}
