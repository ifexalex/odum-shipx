/**
 * API types and bindings for the Payment Release service (release notes + pickup).
 *
 * Wire-format notes:
 *  - authorized_at is an ISO datetime string.
 *  - carton_count / total_cartons_for_customer are plain JSON numbers (not Decimal).
 *  - amount_paid_ngn / balance_ngn / total_ngn are Decimal-as-string, same
 *    convention as every other money field in this app — never parse with
 *    Number() for display, only for arithmetic (see api/decimal.ts if math
 *    is ever needed here; today these are display-only).
 *  - pickup response returns remaining_cartons (int) and optional shipment_status.
 *
 * Ground-truth gap found live, against a real paper "Goods Release Note"
 * reference the user shared: warehouse_address/name/phone, credit/receipt
 * info, physical_document_number, packing_list_invoice_numbers, and the
 * billing amounts were already returned by the backend (or fixed to be, in
 * the same pass) but this type never declared them, so nothing downstream
 * could render them. See 13_api_payment_release.md's matching section.
 */

import { apiDownloadFile, apiRequest, apiRequestList } from './client'

// ---------------------------------------------------------------------------
// Enums
// ---------------------------------------------------------------------------

export type ReleaseNoteStatus = 'active' | 'picked_up' | 'expired' | 'cancelled'

export type DelegateIdType = 'national_id' | 'drivers_license' | 'passport'

// ---------------------------------------------------------------------------
// Response shapes
// ---------------------------------------------------------------------------

export interface ReleaseNote {
  id: string
  reference_number: string
  customer_name: string | null
  container_number: string | null
  carton_count: number
  /** Units already picked up against this release note across prior partial pickups. */
  cartons_picked_up?: number
  /** Units still remaining to be picked up on this release note (`carton_count - cartons_picked_up`). */
  cartons_remaining?: number
  total_cartons_for_customer: number
  is_partial_release: boolean
  carton_tags: string[]
  /** Count-based release accounting ("5 of 8 CTNS") — an alternative to
   * carton_tags for bulk-quantity manifest data with no per-carton tags. */
  packages_released: number | null
  package_unit: string | null
  packages_balance: number | null
  payment_status: string
  status: ReleaseNoteStatus
  authorized_at: string
  warehouse_address: string | null
  warehouse_name: string | null
  warehouse_phone: string | null
  /** True when this release went out before the balance was fully paid —
   * the paper form's "ON CREDIT" state. */
  is_on_credit: boolean
  credit_granted_by_name: string | null
  /** Set once a payment_record is linked (e.g. a subsequent payment settles
   * the balance) — the paper form's "Reciept No." field. */
  receipt_number: string | null
  /** The pre-printed serial number off a physical release-note booklet, when
   * staff transcribe one at issuance — purely informational, never
   * generated by this app (reference_number is the real identifier). */
  physical_document_number: string | null
  packing_list_invoice_numbers: string[]
  amount_paid_ngn: string
  balance_ngn: string
  total_ngn: string
  /** The paper form's "Debt Payment Date" — only set when is_on_credit and an
   * outstanding balance was carried over. ISO date string (YYYY-MM-DD). */
  debt_due_date: string | null
  /** ISO date string (YYYY-MM-DD). Set on creation; expiry job uses it to flip status to 'expired'. Detail responses only. */
  valid_until?: string | null
  /** ISO datetime string when the note transitioned to 'expired' (proxy: updated_at). Detail responses only. */
  expired_at?: string | null
  /** ISO datetime string when the note was fully picked up (proxy: updated_at). Feeds the warehouse done-today count. */
  picked_up_at?: string | null
  /** Outstanding storage fees on the linked billing record — shown on expired UI. Detail responses only. */
  storage_fees_ngn?: string
  /** The warehouse must ask the collector for the pickup code sent to the customer (audit UX-09). */
  pickup_code_required?: boolean
  /** Too many wrong codes: no pickup until staff send a new code. */
  pickup_code_locked?: boolean
  /** ID of the note this was reissued from (or the parent split note). Detail responses only. */
  parent_release_note_id?: string | null
}

export interface PickupResult {
  release_note_id: string
  release_note_status: ReleaseNoteStatus
  pickup_record_id: string
  pickup_date: string
  pickup_time: string | null
  attendant_name: string | null
  customer_service_officer_name: string | null
  accounting_officer_name: string | null
  collected_by_name?: string | null
  delegate_phone?: string | null
  remaining_cartons: number
  shipment_status: string | null
}

// ---------------------------------------------------------------------------
// Request bodies
// ---------------------------------------------------------------------------

export interface CreateReleaseNoteInput {
  billing_id: string
  carton_tags: string[]
  packages_released?: number
  package_unit?: string
  release_with_outstanding?: boolean
  approval_notes?: string
  warehouse_id?: string
  physical_document_number?: string
  /** Required by the backend when release_with_outstanding is true. */
  credit_granted_by_name?: string
  /** ISO date string (YYYY-MM-DD) — the paper form's "Debt Payment Date". */
  due_date?: string
  packing_list_invoice_numbers?: string[]
}

export interface RecordPickupInput {
  cartons_released: number
  is_delegate?: boolean
  // Required by the backend when is_delegate is false (RecordPickupRequest's
  // _require_collector_name_for_non_delegate) — added here because it was
  // missing entirely, silently breaking every non-delegate pickup (the
  // customer collecting in person) with a raw validation crash.
  collected_by_name?: string
  delegate_name?: string
  delegate_phone?: string
  delegate_id_type?: DelegateIdType
  delegate_id_number?: string
  warehouse_id?: string
  customer_service_officer_id?: string
  accounting_officer_id?: string
  warehouse_attendant_id?: string
  notes?: string
  /** The code the collector gives. Needed when the note has `pickup_code_required`. */
  pickup_code?: string
}

/** Where a newly issued pickup code was sent. The code itself is never returned. */
export interface PickupCodeSent {
  release_note_id: string
  sent_via: string[]
}

export interface SplitReleaseNoteInput {
  carton_tags: string[]
  notes?: string
}

// ---------------------------------------------------------------------------
// Query params
// ---------------------------------------------------------------------------

export interface ReleaseNoteListParams {
  status?: ReleaseNoteStatus
  customer_id?: string
  container_id?: string
  /** Exact reference_number match — the warehouse scan-or-type lookup (P2-2). */
  reference?: string
  cursor?: string
  limit?: number
}

// ---------------------------------------------------------------------------
// API bindings
// ---------------------------------------------------------------------------

export const releaseNotesApi = {
  list: (params: ReleaseNoteListParams = {}) =>
    apiRequestList<ReleaseNote>({
      method: 'GET',
      path: '/v1/release-notes',
      query: params as Record<string, string | number | undefined>,
    }),

  get: (id: string) =>
    apiRequest<ReleaseNote>({ method: 'GET', path: `/v1/release-notes/${id}` }),

  /** Per-status counts for the §9.1 stats row (P2-3). Staff/warehouse only. */
  stats: () =>
    apiRequest<{ active: number; partial_active: number; picked_up_today: number; picked_up: number; expired: number }>({
      method: 'GET',
      path: '/v1/release-notes/stats',
    }),

  create: (body: CreateReleaseNoteInput) =>
    apiRequest<ReleaseNote>({ method: 'POST', path: '/v1/release-notes', body }),

  recordPickup: (id: string, body: RecordPickupInput) =>
    apiRequest<PickupResult>({ method: 'PATCH', path: `/v1/release-notes/${id}/release`, body }),

  split: (id: string, body: SplitReleaseNoteInput) =>
    apiRequest<ReleaseNote>({ method: 'POST', path: `/v1/release-notes/${id}/split`, body }),

  /** PDF export — opens in new browser tab (printable pickup authorisation). */
  pdf: (id: string) =>
    apiDownloadFile(`/v1/release-notes/${id}/pdf`, 'pdf', `release-note-${id}.pdf`),

  /** Send the customer a fresh pickup code. The old code stops working and a locked note is unlocked. */
  sendPickupCode: (id: string) =>
    apiRequest<PickupCodeSent>({ method: 'POST', path: `/v1/release-notes/${id}/pickup-code`, body: {} }),

  /** Re-issue an expired release note with a fresh 14-day validity window. */
  reissue: (id: string) =>
    apiRequest<ReleaseNote>({ method: 'POST', path: `/v1/release-notes/${id}/reissue`, body: {} }),
}
