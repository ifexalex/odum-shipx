"""Tenant management: one entry point over the sub-domain modules (audit BE-13).

``service.py`` was one 3,041-line module. The code now lives by sub-domain, and this module re-exports every public
function so the handler, other services and tests keep calling ``service.<name>``:

* ``tenants``: tenant creation and lifecycle, onboarding leads, platform dashboard and activity.
* ``offboarding_export``: a leaving tenant's data export (BE-10).
* ``activation``: account activation and the audit record for access emails.
* ``users``: staff users.
* ``customers``: customer records, GDPR erasure and export, self-registration, invites.
* ``tenant_config``: configuration keys, webhook, Paystack, notification templates, report.
* ``rates``: dollar-rate markup, CBM rates, charge types, container capacities.
* ``platform``: platform settings, plans, quota overrides, notification gateways.

Patch a collaborator (``log_audit``, ``get_identity_provider``, ...) on the module that calls it, not here: a name
re-exported here is a separate binding.
"""

